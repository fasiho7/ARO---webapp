import type { Roadmap, RoadmapNode } from "./types";

function nodes(
  section: string,
  titles: string[],
  statusForIndex: (index: number) => RoadmapNode["status"],
): RoadmapNode[] {
  return titles.map((title, index) => ({
    id: `${section}-${index + 1}`,
    title,
    status: statusForIndex(index),
    section,
  }));
}

